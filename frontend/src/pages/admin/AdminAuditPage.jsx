import { useEffect, useState } from "react";

import api from "../../api/client";
import AdminShell from "../../components/AdminShell";
import { AdminBadge, AdminSection, AdminTable, formatDate } from "../../components/AdminUI";
import Icon from "../../components/Icon";
import { Alert, EmptyState, LoadingState } from "../../components/UI";
import { apiErrorMessage } from "../../utils/validation";

export default function AdminAuditPage() {
  const [page, setPage] = useState({ items: [], total: 0, limit: 100, offset: 0 });
  const [search, setSearch] = useState("");
  const [severity, setSeverity] = useState("");
  const [action, setAction] = useState("");
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");

  async function load() {
    setLoading(true);
    try {
      const response = await api.get("/admin/audit", {
        params: {
          search: search.trim() || undefined,
          severity: severity || undefined,
          action: action.trim() || undefined,
          limit: 200,
        },
      });
      setPage(response.data);
      setError("");
    } catch (requestError) {
      setError(apiErrorMessage(requestError, "Could not load the platform audit log."));
    } finally {
      setLoading(false);
    }
  }

  useEffect(() => { load(); }, [severity]);

  async function download(format) {
    try {
      const response = await api.get("/admin/audit/export", { params: { format }, responseType: "blob" });
      const url = URL.createObjectURL(response.data);
      const link = document.createElement("a");
      link.href = url;
      link.download = `atlas-platform-audit.${format}`;
      document.body.appendChild(link);
      link.click();
      link.remove();
      URL.revokeObjectURL(url);
    } catch (requestError) {
      setError(apiErrorMessage(requestError, "Could not export the audit log."));
    }
  }

  return (
    <AdminShell title="Platform audit log" description="Review authentication, account, project, session, role, and settings events generated by real platform activity." actions={<><button type="button" onClick={() => download("csv")} className="atlas-button-secondary"><Icon name="download" className="h-4 w-4" />CSV</button><button type="button" onClick={() => download("json")} className="atlas-button-secondary"><Icon name="download" className="h-4 w-4" />JSON</button></>}>
      {error && <Alert type="error" onClose={() => setError("")}>{error}</Alert>}
      <AdminSection title="Security and operations history" description={`${page.total} matching event(s). Newest events appear first.`}>
        <form onSubmit={(event) => { event.preventDefault(); load(); }} className="admin-filter-bar admin-filter-bar-audit">
          <label className="admin-filter-search"><Icon name="search" className="absolute left-3 top-1/2 h-4 w-4 -translate-y-1/2 text-slate-400" /><input className="atlas-input !mt-0 !pl-10" value={search} onChange={(event) => setSearch(event.target.value)} placeholder="Search action, user, email, or project" /></label>
          <input className="atlas-input !mt-0 admin-filter-control" value={action} onChange={(event) => setAction(event.target.value)} placeholder="Exact action filter" />
          <select className="atlas-select !mt-0 admin-filter-control" value={severity} onChange={(event) => setSeverity(event.target.value)}><option value="">All severities</option><option value="info">Info</option><option value="warning">Warning</option><option value="critical">Critical</option></select>
          <button type="submit" className="atlas-button-primary admin-filter-submit"><Icon name="search" className="h-4 w-4" />Filter</button>
        </form>
        {loading ? <LoadingState label="Loading audit events..." /> : page.items.length === 0 ? <EmptyState icon="history" title="No matching audit events" description="Administrative and authentication activity will appear here." /> : (
          <AdminTable className="admin-table-audit" label="Platform audit events">
            <thead><tr><th>Time</th><th>Severity</th><th>Action</th><th>Actor</th><th>Target</th><th>Project</th><th>IP</th><th>Details</th></tr></thead>
            <tbody>{page.items.map((event) => (
              <tr key={event.id}>
                <td className="admin-cell-nowrap">{formatDate(event.created_at, true)}</td>
                <td className="admin-cell-nowrap"><AdminBadge value={event.severity} /></td>
                <td className="admin-audit-action-cell"><span className="font-black text-slate-800">{event.action.replaceAll(".", " · ").replaceAll("_", " ")}</span></td>
                <td className="admin-audit-actor-cell">{event.actor_name || "System"}<small className="admin-audit-email block text-slate-400">{event.actor_email || ""}</small></td>
                <td className="admin-cell-nowrap">{event.target_user_name || "—"}</td>
                <td className="admin-audit-project-cell">{event.project_name || "—"}</td>
                <td className="admin-cell-ip">{event.ip_address || "—"}</td>
                <td><code className="admin-json-preview">{JSON.stringify(event.details)}</code></td>
              </tr>
            ))}</tbody>
          </AdminTable>
        )}
      </AdminSection>
    </AdminShell>
  );
}
